/**
 * Toolroom £/hr in a region vs the UK. A toolroom hour is about half skilled
 * labour (toolmaker, fitter, polisher) and half machine (CNC, EDM, spotting
 * press), so the factor is the mean of the skilled-labour ratio and the
 * machine-rate multiplier. China: ½ × 8.08/26.19 + ½ × 0.55 = 0.43. The
 * comparison table scales tooling by the same factor, so the two regional
 * paths agree. An estimate — a toolmaker's quote replaces it.
 */
export function toolroomFactorFor(region: ManufacturingRegion): number {
  const rd = REGIONAL_DATA[region];
  if (!rd || region === 'UK') return 1;
  // a toolmaker's selling rate sourced in the country and in the UK outranks the derived ratio (round 30 Oct 2026)
  const sourced = sourcedServiceFactor(region, 'toolroom');
  if (sourced) return sourced.factor;
  return Math.round((0.5 * rd.labour.skilled / REGIONAL_DATA.UK.labour.skilled + 0.5 * rd.machineRateMultiplier) * 10_000) / 10_000;
}

/**
 * Overhead %, packaging and logistics £/part for a region — the screen's country
 * switch and headless costing both read this, so the same part costs the same
 * in China on either path. Overhead 12 % × the region's multiplier. Packaging and
 * logistics are the UK-basis figure × the region's multipliers (logistics is
 * delivery to the UK): the size-aware estimate when the part's geometry gave one
 * (`estimatePackagingPerPart` / `estimateLogisticsPerPart`), else £0.15 / £0.25.
 * The screen used to overwrite a size-aware estimate with the flat £0.15 × factor.
 */
export function regionalShopDefaults(
  region: ManufacturingRegion,
  ukBasis: { packagingPerPart?: number; logisticsPerPart?: number } = {},
  terms: DeliveryTerms = 'DAP',
): { overheadPct: number; packagingPerPart: number; logisticsPerPart: number } {
  const rd = REGIONAL_DATA[region] ?? REGIONAL_DATA.UK;
  const r4 = (n: number) => Math.round(n * 10_000) / 10_000;
  return {
    overheadPct: Math.round(12 * rd.overheadMultiplier) / 100,
    packagingPerPart: r4((ukBasis.packagingPerPart ?? 0.15) * rd.packagingMultiplier),
    // ex-works: the buyer collects at the gate — packaging is in the price, freight is not
    logisticsPerPart: terms === 'EXW' ? 0 : r4((ukBasis.logisticsPerPart ?? 0.25) * rd.logisticsMultiplier),
  };
}

/** What the delivery terms mean, for the reports and the cost card. */
export function deliveryTermsLine(terms: DeliveryTerms | undefined): string {
  return terms === 'EXW'
    ? 'Ex-works (EXW): the price at the supplier\'s gate — packaging included, freight to your plant NOT included (logistics 0)'
    : 'Delivered to your plant (DAP): the logistics line is the freight to your plant';
}

/** Where the overhead / packaging / logistics DEFAULTS come from — the reports printed them with no basis (Germany review). */
export function shopDefaultsBasis(region: ManufacturingRegion | undefined, terms: DeliveryTerms = 'DAP'): string {
  const rd = REGIONAL_DATA[region ?? 'UK'] ?? REGIONAL_DATA.UK;
  const f = (n: number) => `×${n.toFixed(2)}`;
  const exw = terms === 'EXW';
  const sized = exw ? 'packaging from the part\'s size' : 'packaging and logistics from the part\'s size';
  const freight = exw ? ' Ex-works: no freight in the price (logistics 0).' : '';
  return (region && region !== 'UK'
    ? `Defaults: the UK basis (overhead 12%, ${sized}) × ${rd.name}'s multipliers — overhead ${f(rd.overheadMultiplier)}, packaging ${f(rd.packagingMultiplier)}`
      + (exw ? '' : `, logistics ${f(rd.logisticsMultiplier)} (delivery to the UK)`)
      + `. ${rd.shopMultipliersBasis ?? `Held, not researched for ${rd.name}`}; a typed figure is used as given.`
    : `Defaults: overhead 12%; ${sized}${exw ? '' : ' (delivery within the UK)'}. A typed figure is used as given.`) + freight;
}

export function buildRegionalLibrary(baseLibrary: RateLibrary, region: ManufacturingRegion): RateLibrary {
  const rd = REGIONAL_DATA[region];
  // The country's own book (country-books.ts) wins where it has evidence; the scaling below is the fallback.
  const book = COUNTRY_BOOKS[region];
  const ownEnergy = baseLibrary.energy.find(e => e.id === `energy-${region.toLowerCase()}`);
  const elecTariff = ownEnergy?.electricityPerKwh ?? rd.energy.electricityPerKwh;

  // Derive labour rates from the ID suffix (lab-{region}-{category} → rd.labour[category]).
  // Any ID whose suffix matches a known category gets the target region's rate for that category;
  // unrecognised suffixes fall back to the proportional formula below.
  const labourCategoryRates: Record<string, number> = {
    skilled:     rd.labour.skilled,
    semiskilled: rd.labour.semiskilled,
    engineer:    rd.labour.engineer,
    foundry:     rd.labour.foundry,
    electronics: rd.labour.electronics,
    inspector:   rd.labour.inspector,
    technician:  rd.labour.technician,
    supervisor:  rd.labour.supervisor,
  };

  // Family-aware material factor: resins priced by family; exchange-traded metals
  // (Al/Ti/Ni/Cu/Mg) use the near-flat global compression (same as high-perf resin);
  // mill steel and everything else use the regional index.
  const materialFactorFor = (m: MaterialRate): number => {
    switch (classifyMaterialFamily(m)) {
      case 'commodity':       return rd.materialFactors.commodityResin;
      case 'engineering':     return rd.materialFactors.engineeringResin;
      case 'highPerformance': return rd.materialFactors.highPerfResin;
      case 'exchangeMetal':   return rd.materialFactors.highPerfResin; // global market → ~flat
      case 'rubber':          return rd.materialFactors.highPerfResin; // globally-traded gum → ~flat
      case 'millSteel':       return rd.materialMultiplier;
      default:                return rd.materialMultiplier;
    }
  };

  return {
    ...baseLibrary,
    version: `${baseLibrary.version}-${region}`,
    lastModified: new Date().toISOString().slice(0, 10),
    regional: { code: region, name: rd.name, toolroomFactor: toolroomFactorFor(region) },

    // Labour: a grade named by its category (lab-{region}-{category}) takes the
    // region's rate for that category. A process grade (lab-uk-forge, -blow, ...)
    // keeps its premium over its category and moves by that category's ratio —
    // it used to move by the SKILLED ratio whatever it was, and an operator grade
    // is not a skilled one.
    labour: baseLibrary.labour.map(l => {
      const suffix = l.id.replace(/^lab-[a-z]+-/, '');
      // The book's OWN rate for this role in this country wins (a company book's
      // lab-cn-skilled from a supplier audit) — the regional table is the default
      // where the book has none. It used to be ignored.
      const own = region !== 'UK' ? baseLibrary.labour.find(x => x.id === `lab-${region.toLowerCase()}-${suffix}`) : undefined;
      if (own) {
        // the row's date is the rate's own — a German report dated its book rates with the UK entry's date (Germany review)
        return { ...l, fullyLoadedRatePerHr: own.fullyLoadedRatePerHr, region: rd.name, effectiveDate: own.effectiveDate ?? l.effectiveDate,
          sourceNote: `${own.id} — the rate book's own ${rd.name} rate (${own.sourceNote ?? ''})`.trim(), confidence: own.confidence };
      }
      const grade = book?.labourGrades[suffix];
      if (grade) {
        return { ...l, fullyLoadedRatePerHr: grade.gbpPerHr, region: rd.name, effectiveDate: book!.asOf,
          // the book's own currency (a China report read "furnace INR 32/h" — demo review 2026-10-10)
          sourceNote: `${rd.name} book ${book!.asOf}: ${suffix} ${book!.currencySymbol ?? '₹'}${(grade.gbpPerHr * book!.fxToGBP).toFixed(2)}/h — ${grade.basis} (${grade.source})`,
          confidence: grade.confidence };
      }
      const direct = labourCategoryRates[suffix];
      const cat = PROCESS_LABOUR_CATEGORY[suffix] ?? 'skilled';
      const rate = direct ?? Math.round(l.fullyLoadedRatePerHr * (rd.labour[cat] / REGIONAL_DATA.UK.labour[cat]) * 100) / 100;
      return {
        ...l,
        fullyLoadedRatePerHr: rate,
        region: rd.name,
        ...(book && direct !== undefined ? { effectiveDate: book.asOf } : {}),
        sourceNote: direct !== undefined
          // a book country's category rate is its rate book's (a China report read "China foundry rate (regional-rates.ts, 2026-09)")
          ? (book ? `${rd.name} rate book ${book.asOf}: ${suffix} ${rd.currency} ${(direct * rd.fxToGBP).toFixed(2)}/h fully loaded (the rate book's labour model)`
            : `${rd.name} ${suffix} labour rate — regional table (2026-09 refresh)`)
          : `UK ${suffix} grade × ${rd.name}/UK ${cat} ratio ${(rd.labour[cat] / REGIONAL_DATA.UK.labour[cat]).toFixed(4)}`,
        confidence: 'Low' as const,
      };
    }),

    // Adjust material prices. Extrusion grades with an authentic per-country
    // price use it directly (a real regional quote, not "UK × factor"); scrap
    // recovery is scaled by the same authentic/UK ratio so the recovery credit
    // tracks the local resin value. Everything else uses the resin family-aware
    // factor (metals/other flat).
    materials: baseLibrary.materials.map(m => {
      // Aluminium extrusion billet: LME + THIS region's all-in billet premium + the
      // alloy adder (al-extrusion-data.ts) — a US billet carries the Midwest premium,
      // a Chinese one sits under LME. The scrap value is LME-based, so it stays.
      const alAlloy = m.id.startsWith('mat-al-billet-')
        ? (Object.keys(AL_ALLOYS) as AlAlloy[]).find(a => `mat-al-billet-${a.toLowerCase()}` === m.id) : undefined;
      if (alAlloy) {
        const p = billetPriceGbpPerKg(alAlloy, region);
        return { ...m, pricePerKg: p, region: rd.name, confidence: 'Medium' as const,
          // The region's OWN build-up — the UK note ("UK all-in billet premium $1100/t … UK imports billet") was kept and
          // this appended, so a German report printed two premiums (Germany live review, Oct 2026).
          sourceNote: `${rd.name}: LME $${AL_MARKET.lmeUsdPerT}/t + ${rd.name} billet premium $${BILLET_PREMIUM_USD_PER_T[region].usdPerT}/t `
            + `(${BILLET_PREMIUM_USD_PER_T[region].basis}) + ${alAlloy} alloy adder $${AL_ALLOYS[alAlloy].billetAdderUsdPerT}/t (engineering estimate) `
            + `at $${AL_MARKET.usdPerGbp}/£ = £${p.toFixed(3)}/kg. Scrap at LME ${AL_ALLOYS[alAlloy].scrapDiffUsdPerT >= 0 ? '+' : '−'} $${Math.abs(AL_ALLOYS[alAlloy].scrapDiffUsdPerT)}/t, the same in every region (scrap trades on LME terms).` };
      }
      const own = book ? countryMaterial(book, m, rd.name) : null;
      if (own) return own;
      const authentic = EXTRUSION_COUNTRY_PRICES[m.id]?.[region] ?? THERMOFORMING_COUNTRY_PRICES[m.id]?.[region];
      if (authentic !== undefined) {
        const ratio = m.pricePerKg > 0 ? authentic / m.pricePerKg : 1;
        return {
          ...m,
          pricePerKg: authentic,
          scrapRecoveryPricePerKg: m.scrapRecoveryPricePerKg * ratio,
          region: rd.name,
          // the country leads: a report in this country must not open a material line with a UK source (demo review 2026-10-10)
          sourceNote: `${rd.name}: country price £${authentic.toFixed(2)}/kg (2026-09, country-specific, not multiplier-scaled). UK basis: ${m.sourceNote}`,
          confidence: 'Low' as const,
        };
      }
      const f = materialFactorFor(m);
      return {
        ...m,
        pricePerKg: m.pricePerKg * f,
        scrapRecoveryPricePerKg: m.scrapRecoveryPricePerKg * f,
        region: rd.name,
        sourceNote: f === 1
          // at par (Hungary book): no unsourced country discount — the European-market price as the book holds it
          ? `${rd.name}: no ${rd.name} price for this grade — the book's European-market price £${m.pricePerKg.toFixed(2)}/kg at par (no country factor). UK basis: ${m.sourceNote}`
          : `${rd.name}: no ${rd.name} price for this grade — the UK book £${m.pricePerKg.toFixed(2)}/kg × ${f.toFixed(3)} `
            + `(${classifyMaterialFamily(m)} country factor). UK basis: ${m.sourceNote}`,
        // a country WITH its own rate book looked for this grade and found no price: UK × a factor is Low there
        // (a Poland ECU cover's resin — 53% of the part — printed "Medium" on a UK price × 0.97; live review 10 Oct 2026)
        ...(book ? { confidence: 'Low' as const } : {}),
      };
    }),

    // Adjust machine rates: scale capex/overhead by machineRateMultiplier, and
    // re-tariff the energy component at the region's actual electricity price so
    // a cheap-power region (e.g. DE 0.20 vs UK 0.23) is genuinely cheaper to run.
    // The £/hr is recomputed from the rebuilt build-up (single source of truth).
    machines: baseLibrary.machines.map(m => {
      const own = book && m.buildup ? countryMachine(book, m, baseLibrary.machines, elecTariff, rd.name) : null;
      if (own) return own;
      if (!m.buildup) {
        // No build-up to rebuild from — fall back to the flat capex scale.
        return {
          ...m,
          computedRatePerHr: m.computedRatePerHr * rd.machineRateMultiplier,
          region: rd.name,
          sourceNote: `${rd.name}: the UK rate × ${rd.machineRateMultiplier} (no build-up to rebuild). UK basis: ${m.sourceNote}`,
          confidence: 'Low' as const,
        };
      }
      const b = m.buildup;
      const annualKwh = b.energy / UK_ELECTRICITY_BASIS_PER_KWH;      // back out kWh from UK-basis £
      const regionalEnergy = annualKwh * elecTariff; // re-tariff at the country's £/kWh
      const rebuilt = {
        ...b,
        annualDepreciation: b.annualDepreciation * rd.machineRateMultiplier,
        maintenance:        b.maintenance        * rd.machineRateMultiplier,
        floorSpace:         b.floorSpace          * rd.machineRateMultiplier,
        indirectSupport:    b.indirectSupport     * rd.machineRateMultiplier,
        financeCost:        b.financeCost         * rd.machineRateMultiplier,
        energy:             regionalEnergy,
      };
      return {
        ...m,
        buildup: rebuilt,
        computedRatePerHr: computeMachineRatePerHr(rebuilt),
        region: rd.name,
        // the country leads (demo review 2026-10-10: a Germany report opened a machine line with "UK book … Capex £77,006")
        sourceNote: `${rd.name}: the UK build-up with capital and overhead × ${rd.machineRateMultiplier} and energy at `
          + `${rd.currency} ${(elecTariff * rd.fxToGBP).toFixed(3)}/kWh (£${elecTariff}). UK basis: ${m.sourceNote}`,
        confidence: 'Low' as const,
      };
    }),

    // Energy: the book's own tariff for this country wins (energy-<cc>), else the regional table.
    energy: [
      {
        id: `energy-${region.toLowerCase()}`,
        region: rd.name,
        electricityPerKwh: ownEnergy?.electricityPerKwh ?? rd.energy.electricityPerKwh,
        gasPerKwh: ownEnergy?.gasPerKwh ?? rd.energy.gasPerKwh,
        // the book's own energy-<cc> entry carries its date and source (the China / India rate books) — it was replaced by
        // "industrial energy benchmark 2026-09" stamped with today's date
        effectiveDate: ownEnergy?.effectiveDate ?? '2026-09',
        sourceNote: ownEnergy?.sourceNote ?? `${rd.name} industrial energy benchmark 2026-09`,
        confidence: (ownEnergy?.confidence ?? 'Low') as 'High' | 'Medium' | 'Low',
      },
    ],
  };
}

/**
 * Get per-region packaging and logistics defaults.
 * Includes cross-region shipping premium when manufacturing region differs from delivery (UK).
 */
export function getRegionalLogistics(
  mfgRegion: ManufacturingRegion,
  basePackaging: number,
  baseLogistics: number
): { packaging: number; logistics: number } {
  const rd = REGIONAL_DATA[mfgRegion];
  return {
    packaging: basePackaging * rd.packagingMultiplier,
    logistics: baseLogistics * rd.logisticsMultiplier,
  };
}

// ─── Regional cost comparison ───────────────────────────────────────────────────
// Scales an 8-bucket should-cost across regions using the per-region multipliers,
// so the same figures back the on-screen table and the PDF export. Ex-Works by
// default; pass { landed: true } to add import duty + international freight.

export interface RegionalComparisonRow {
  code: ManufacturingRegion;
  name: string;
  currency: string;
  material: number; process: number; labour: number; tooling: number; overhead: number;
  exWorks: number; packaging: number; logistics: number; margin: number; total: number;
  vsBasePct: number;   // (baseTotal − total) / baseTotal × 100 — positive = cheaper than base
  isBase: boolean;
  /**
   * How the row was made, so a report can say it: 'costed' — the costing itself; 'chain' — the part costed through the
   * whole chain with that country selected; 'stack-reprice' — the costing's operations and material weight re-priced in
   * that country's book, per-part services, consumables, a module-priced material and the module's own choices carried
   * from the costing country (up to ±100 % off the chain on a direct-priced composite; arithmetic audit, 30 Oct 2026);
   * 'scaled' — the buckets scaled by the country's multipliers (no book at all).
   */
  basis?: 'costed' | 'chain' | 'stack-reprice' | 'scaled';
}


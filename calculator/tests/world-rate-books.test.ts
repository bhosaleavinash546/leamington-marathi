/**
 * World rate round (30 Oct 2026): every one of the 39 countries is costed on its OWN rate book. The 33 books of this
 * round are generated from `scripts/rate-refresh/2026-10-world-<cc>.json` (scripts/rate-refresh/world-2026-10/
 * build-world.py → scripts/country-book.ts). This proves, for every one of them:
 *   - the book is generated, registered and dated, at the FX its config states (and REGIONAL_DATA carries);
 *   - labour is the config's arithmetic (every category sourced, none "HELD");
 *   - what no research priced is AT PAR — machine capital ×1 and materials at the book's own price, never an
 *     unsourced UK multiplier;
 *   - every machine and labour rate on real parts costed in that country is that country's book.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync, readdirSync } from 'node:fs';
import { COUNTRY_BOOKS } from '../src/engine/country-books.js';
import { WORLD_BOOKS } from '../src/engine/country-books/world.js';
import { REGIONAL_DATA, REGION_NAMES, buildRegionalLibrary, type ManufacturingRegion } from '../src/engine/regional-rates.js';
import { DEFAULT_RATE_LIBRARY, recomputeMachineRates } from '../src/engine/rate-library.js';
import { costMeasuredPart } from '../server/services/bulk-run.js';

const UK = recomputeMachineRates(DEFAULT_RATE_LIBRARY);
const CFGS = readdirSync('scripts/rate-refresh').filter(f => /^2026-10-world-[a-z]{2}\.json$/.test(f))
  .map(f => JSON.parse(readFileSync(`scripts/rate-refresh/${f}`, 'utf8')));
const ALL = Object.keys(REGION_NAMES) as ManufacturingRegion[];

describe('every country has its own rate book', () => {
  it('39 countries: the UK base book + 38 country books (33 from the world round)', () => {
    expect(ALL).toHaveLength(39);
    expect(CFGS).toHaveLength(33);
    for (const c of ALL) if (c !== 'UK') expect(COUNTRY_BOOKS[c], c).toBeDefined();
    expect(Object.keys(WORLD_BOOKS).sort()).toEqual(CFGS.map(c => c.region).sort());
  });

  for (const cfg of CFGS) {
    const cc = cfg.region as ManufacturingRegion;
    describe(`${cc} ${REGIONAL_DATA[cc].name}`, () => {
      const book = COUNTRY_BOOKS[cc]!;
      it('generated from its dated config, at the config FX', () => {
        expect(book.asOf).toBe('2026-10-30');
        expect(readFileSync(cfg.bookFile, 'utf8')).toMatch(/GENERATED by `scripts\/country-book\.ts`/);
        expect(REGIONAL_DATA[cc].fxToGBP).toBeCloseTo(cfg.fxPerGbp, 3);
        expect(cfg.fxBasis).toBeTruthy();
      });
      it('labour is the config\'s sourced arithmetic, every category', () => {
        for (const k of ['skilled', 'semiskilled', 'foundry', 'electronics', 'inspector', 'technician', 'supervisor', 'engineer'] as const) {
          const c = cfg.labour.categories[k];
          expect(REGIONAL_DATA[cc].labour[k], k).toBeCloseTo(c.localPerHr / cfg.fxPerGbp, 3);
          expect(c.basis, k).not.toMatch(/^HELD/);
          expect(c.source, k).toMatch(/https?:\/\//);
        }
      });
      it('no unsourced UK factor: capital and unpriced materials AT PAR', () => {
        expect(book.machines.capitalHeldFactor).toBe(1);
        expect(REGIONAL_DATA[cc].materialMultiplier).toBe(1);
        expect(REGIONAL_DATA[cc].materialFactors).toEqual({ commodityResin: 1, engineeringResin: 1, highPerfResin: 1 });
        const lib = buildRegionalLibrary(UK, cc);
        for (const m of lib.materials) {
          if (book.materials[m.id] || /^mat-al-billet-/.test(m.id) || /country price/.test(m.sourceNote)) continue;
          expect(m.sourceNote, m.id).toMatch(/at par \(no country factor\)/);
        }
        const held = lib.machines.filter(m => /capital AT PAR/.test(m.sourceNote ?? ''));
        expect(held.length + book.machines.groups.length).toBeGreaterThan(0);
      });
      it('every operating-model input has a stated basis (hours, life, finance, rent, energy)', () => {
        const M = cfg.machines;
        for (const k of ['hoursBasis', 'financeBasis', 'rentBasis', 'shiftBasis']) expect(M[k], k).toBeTruthy();
        expect(M.lifeYears).toBeGreaterThan(2);
        expect(M.financeRate).toBeGreaterThan(0);
        expect(cfg.energy.basis).toBeTruthy();
      });
    });
  }
});

describe('every rate line of real parts costed in each country is that country\'s book', () => {
  const baseline = JSON.parse(readFileSync('tests/fixtures/real-parts-baseline.json', 'utf8')) as
    { part: string; answers: Record<string, string>; geometry: never; outcome: { commodity?: string } }[];
  // one part a costing route, so the test touches every commodity without costing 40 parts × 39 countries
  const seen = new Set<string>();
  const sample = baseline.filter(p => { const k = p.outcome.commodity ?? p.part; if (seen.has(k)) return false; seen.add(k); return true; });
  for (const cc of ALL.filter(c => c !== 'UK')) {
    it(`${cc}`, async () => {
      const lib = buildRegionalLibrary(UK, cc);
      const bad: string[] = [];
      let costed = 0;
      for (const p of sample) {
        const r = await costMeasuredPart(p.geometry, p.part, { partNumber: p.part, file: p.part, annualVolume: 50_000,
          ...(p.outcome.commodity ? { commodity: p.outcome.commodity } : {}) },
        p.answers, cc, { annualVolume: 50_000, deliveryTerms: 'EXW' }, UK, { partNumber: p.part, file: p.part, status: 'error' });
        if (r.status !== 'costed') continue;
        costed++;
        expect(r.trace!.rateBook, p.part).toMatch(new RegExp(`-${cc}$`));
        for (const o of r.trace!.operations) {
          const m = lib.machines.find(x => x.id === o.machineId), l = lib.labour.find(x => x.id === o.labourId);
          if (m && Math.abs(o.machineRateUsed - m.computedRatePerHr) > 1e-6) bad.push(`${p.part} ${o.operationName} machine`);
          if (l && Math.abs(o.labourRateUsed - l.fullyLoadedRatePerHr) > 1e-6) bad.push(`${p.part} ${o.operationName} labour`);
        }
      }
      expect(costed).toBeGreaterThan(5);
      expect(bad).toEqual([]);
    }, 300_000);
  }
});

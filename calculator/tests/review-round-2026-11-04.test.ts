import type { OCCTGeometry } from '../server/utils/geometry-bridge.js';

const RESEARCH = new Map((JSON.parse(readFileSync('scripts/research/2026-11-review-round/data.json', 'utf8')) as Array<{ id: string; value_num: number | null; currency: string | null; gbp_at_book_fx: number | null }>)
  .map(r => [r.id, r]));
const base = JSON.parse(readFileSync('tests/fixtures/real-parts-baseline.json', 'utf8')) as Array<{ part: string; geometry: OCCTGeometry }>;
const book = recomputeMachineRates(DEFAULT_RATE_LIBRARY);
const machine = (id: string) => book.machines.find(m => m.id === id)!;
const ctxOf = (part: string, annualVolume: number, answers: Record<string, string> = ANSWERS[part].answers): RuleContext => ({
  geo: base.find(p => p.part === part)!.geometry, geometryQuality: 'occt', commodity: 'cast_and_machine', commoditySource: 'engineer',
  annualVolume, filename: part, answers,
} as unknown as RuleContext);
const rules = (part: string, annualVolume: number, answers?: Record<string, string>) => runCostInputRules(CAST_AND_MACHINE_RULES, ctxOf(part, annualVolume, answers));
// eslint-disable-next-line @typescript-eslint/no-explicit-any
async function cost(part: string, region: ManufacturingRegion = 'UK', annualVolume = 200_000): Promise<any> {
  const p = base.find(x => x.part === part)!;
  return costMeasuredPart(p.geometry, part, { partNumber: part, file: part, annualVolume } as never, ANSWERS[part].answers, region,
    { annualVolume, programmeYears: 5, deliveryTerms: 'EXW' } as never, book, { partNumber: part, file: part, status: 'error' } as never);
}

describe('1. foundry indirect costs are named rules, each with its value, source and arithmetic', () => {
  it('the constants are the research rows (S2, S3, E1, E2, E3)', () => {
    expect(FOUNDRY_INDIRECT.newSand.shareOfPoured).toBe(0.15);                        // S2: 10–20 % of poured metal
    expect(FOUNDRY_INDIRECT.newSand.sandEurPerT).toBe(RESEARCH.get('S3')!.value_num);  // S3: €45/t new sand
    expect(FOUNDRY_INDIRECT.newSand.disposalEurPerT).toBe(43);                        // S3: €43/t disposal
    expect(NEW_SAND_GBP_PER_T_SAND).toBeCloseTo(88 / 1.1965, 10);
    expect(FOUNDRY_INDIRECT.ladlePreheatKwhPerT.iron.band).toEqual([50, 150]);        // E1
    expect(FOUNDRY_INDIRECT.ladlePreheatKwhPerT.steel.band).toEqual([100, 300]);      // E1
    expect(FOUNDRY_INDIRECT.dustExtractionKwhPerT.value).toBe(RESEARCH.get('E2')!.value_num);
    expect(PLANT_OTHER_KWH_PER_T).toBe(455);                                          // E3 midpoint 0.475 − 0.020 dust
    expect(NEW_SAND_BASIS).toEqual({ globalShare: 0.5114, rest: 'process' });         // 45 / 88 traded, the disposal local
  });

  it('ductile iron (the stub axle): new sand, ladle 100, dust 20, plant 455 — each printing its source', () => {
    const r = rules('PRCR002.stp', 200_000);
    const p = (id: string) => r.provenance[id];
    expect(p('cam-new-sand').value).toBe(11.0322);
    expect(p('cam-new-sand').basis).toMatch(/€45\/t \+ disposal €43\/t = €88\/t; €88 ÷ €1\.1965\/£ = £73\.5478\/t of sand; 0\.15 × £73\.5478 = £11\.0322\/t poured/);
    expect(p('cam-new-sand').basis).toMatch(/BREF 2024 .*DE UBA 2014/);
    expect(p('cam-new-sand').basis).toMatch(/bentonite and coal dust are NOT costed/);
    expect(p('cam-ladle-kwh').value).toBe(100);
    expect(p('cam-ladle-kwh').basis).toMatch(/midpoint of 50–150 kWh\/t for iron foundries/);
    expect(p('cam-ladle-kwh').basis).toMatch(/natural-gas burner assumed \(CostVision engineering judgement, not sourced\)/);
    expect(p('cam-dust-kwh').value).toBe(20);
    expect(p('cam-plant-kwh').value).toBe(455);
    expect(p('cam-plant-kwh').basis).toMatch(/^ESTIMATE \(grade D/);
    expect(p('cam-plant-kwh').basis).toContain(FOUNDRY_NOT_COSTED);
    expect(FOUNDRY_NOT_COSTED).toMatch(/refractory.*metallurgical lab.*pouring and sand-plant crew.*riser cut-off, weld repair and steel refractory/);
  });

  it('cast steel (the bracket) takes the steel ladle figure; an aluminium gravity casting is told what is not costed', () => {
    expect(rules('Casting_Braket.stp', 200_000).provenance['cam-ladle-kwh'].value).toBe(200);
    const al = rules('PRCR002.stp', 200_000, { ...ANSWERS['PRCR002.stp'].answers, 'material.family': 'aluminium' });
    expect(al.suggestions.casting).toMatchObject({ subtype: 'gravity' });
    expect(al.provenance['cam-ladle-kwh'].value).toBe(0);
    expect(al.provenance['cam-ladle-kwh'].basis).toMatch(/NOT costed for this metal/);
    expect(al.provenance['cam-plant-kwh'].value).toBe(0);
    expect(al.provenance['cam-new-sand']).toBeUndefined();   // no green sand on a permanent mould
  });

  it('every rule path reaches headless (RULE_PATH_MAP) and the screen has the four fields on both forms', () => {
    for (const id of ['casting.newSandGbpPerTPoured', 'casting.ladlePreheatKwhPerT', 'casting.dustExtractionKwhPerT', 'casting.plantElectricityKwhPerT']) {
      expect(RULE_PATH_MAP[id], id).toEqual({ to: id });
    }
    const html = readFileSync('src/ui/main.ts', 'utf8');
    for (const pre of ['cast', 'cam']) {
      for (const f of ['new-sand', 'ladle-kwh', 'dust-kwh', 'plant-kwh']) expect(html).toContain(`id="${pre}-${f}"`);
      expect(html).toContain(`foundry: foundryInput({ newSandGbpPerTPoured: num('${pre}-new-sand')`);
      expect(FIELD_BASIS[`${pre}-new-sand`]).toEqual(NEW_SAND_BASIS);
    }
  });

  it('the module: new sand on the kg POURED; ladle gas on the kg poured; dust + plant electricity on the kg of good casting', () => {
    const d = computeCastingDrivers({
      subtype: 'sand', materialId: 'mat-gjs500', partWeightKg: 9, castingYield: 0.6, rejectRate: 0.03,
      labourId: 'lab-uk-foundry', oee: 0.8, manning: 3, labourEfficiency: 0.92, amortizationVolume: 100_000,
      sand: { mouldLineId: 'sand-auto-vertical-line', cycleTimeHr: 0.001, patternCost: 10_000, patternLife: 400_000, coreCostPerPart: 0 },
      foundry: { newSandGbpPerTPoured: 11.0322, ladlePreheatKwhPerTPoured: 100, dustExtractionKwhPerTGood: 20, plantElectricityKwhPerTGood: 455 },
    });
    const pour = 9 / 0.97 / 0.6;
    const melt = d.rawMaterial.energyKwh!.electricity! - 9 * 475 / 1000;
    expect(d.rawMaterial.energyKwh!.gas).toBeCloseTo(pour * 100 / 1000, 10);
    expect(melt).toBeGreaterThan(0);
    expect(d.rawMaterial.consumablesItems!.find(i => /^new sand \+ disposal/.test(i.label))!.gbp).toBeCloseTo(pour * 11.0322 / 1000, 10);
    expect(d.rawMaterial.energyKwh!.basis).toMatch(/ladle preheat \(gas\): .* kg poured × 100 kWh\/t/);
    expect(d.rawMaterial.energyKwh!.basis).toMatch(/other plant electricity beyond melt: 9\.0000 kg good casting × 455 kWh\/t/);
    // no engineering-typical green-sand line any more
    expect(d.rawMaterial.consumablesItems!.some(i => /green-sand/.test(i.label))).toBe(false);
    // a die casting carries none of them, whatever is passed
    const hpdc = computeCastingDrivers({
      subtype: 'hpdc', materialId: 'mat-adc12', partWeightKg: 1, castingYield: 0.8, rejectRate: 0.03, labourId: 'lab-uk-foundry',
      oee: 0.8, manning: 1, labourEfficiency: 0.92, amortizationVolume: 100_000,
      hpdc: { machineId: 'hpdc-800t', cycleTimeSec: 60, cavities: 1, dieCost: 50_000, dieLife: 150_000 },
      foundry: { newSandGbpPerTPoured: 11, ladlePreheatKwhPerTPoured: 100, dustExtractionKwhPerTGood: 20, plantElectricityKwhPerTGood: 455 },
    });
    expect(hpdc.rawMaterial.energyKwh!.gas ?? 0).toBe(0);
    expect(hpdc.rawMaterial.consumablesItems?.some(i => /new sand/.test(i.label)) ?? false).toBe(false);
  });

  it('the energy is kWh priced at each country\'s own tariff (not £ at a passed tariff)', async () => {
    const [uk, cn] = await Promise.all([cost('PRCR002.stp', 'UK'), cost('PRCR002.stp', 'CN')]);
    const kwh = uk.trace.drivers.rawMaterial.energyKwh;
    expect(cn.trace.drivers.rawMaterial.energyKwh.gas).toBeCloseTo(kwh.gas, 10);
    expect(cn.trace.drivers.rawMaterial.energyKwh.electricity).toBeCloseTo(kwh.electricity, 10);
    const gasLine = (r: { trace: { result: { traceability: Array<{ field: string; value: number }> } } }) =>
      r.trace.result.traceability.find(t => t.field === 'rawMaterial.energyKwh.gas')!.value;
    const ukT = buildRegionalLibrary(book, 'UK').energy[0], cnT = buildRegionalLibrary(book, 'CN').energy[0];
    expect(gasLine(uk)).toBeCloseTo(kwh.gas * ukT.gasPerKwh, 6);
    expect(gasLine(cn)).toBeCloseTo(kwh.gas * cnT.gasPerKwh, 6);
    expect(cnT.gasPerKwh).not.toBe(ukT.gasPerKwh);
  }, 60_000);

  it('the report standard lists what the research could not price as "Not in the cost model"', () => {
    for (const c of ['casting', 'cast_and_machine'] as const) {
      const nm = reportStandardFor(c).notModelled!.join(' ');
      expect(nm, c).toMatch(/refractory.*metallurgical lab.*pouring and sand-plant crew.*bentonite.*riser cut-off, weld repair and steel refractory/);
      expect(nm, c).toMatch(/a gap in the cost model/);
    }
  });
});

describe('2. impressions a mould: the free fit, the 60 % plate rule, sand : iron ≥ 5 : 1 — the binding limit printed', () => {
  it('the limits are the research rows S4 (60 %), S5 (70 mm) and S6 (5 : 1); the sand density says it is unsourced', () => {
    expect(IMPRESSION_LIMITS.plateShareMax).toBe(RESEARCH.get('S4')!.value_num);
    expect(IMPRESSION_LIMITS.sandBetweenCavitiesMm).toBe(RESEARCH.get('S5')!.value_num);
    expect(IMPRESSION_LIMITS.sandToIronMin).toBe(RESEARCH.get('S6')!.value_num);
    expect(IMPRESSION_LIMITS.sandDensityBasis).toMatch(/engineering-typical, not sourced/);
  });

  it('the stub axle (ductile iron): 9 fit, the plate allows 6, sand : iron allows 4 — 4, and the sand : iron limit binds', () => {
    const b = String(rules('PRCR002.stp', 200_000).provenance['cam-sand-ct'].basis);
    expect(b).toMatch(/free fit 9 .*60 % plate rule .*→ 6 \(rounded down\).*344\.5 mm thick \(274\.5 mm deep along the draw \+ 70 mm/);
    expect(b).toMatch(/→ 4 \(rounded down\) → 4 — sand : iron 5 : 1 binds/);
  });

  it('the bracket (cast steel): 20 fit, the plate rule binds at 12; sand : iron is not applied to steel', () => {
    const b = String(rules('Casting_Braket.stp', 200_000).provenance['cam-sand-ct'].basis);
    expect(b).toMatch(/free fit 20 .*→ 12 \(rounded down\).*not applied to this metal\) → 12 — the 60 % plate rule binds/);
  });

  it('impressionPlan: each limit by hand', () => {
    const face = SAND_LINE_CLASSES['auto-vertical'].faceMm;     // 950 × 700
    const p = impressionPlan([222.36, 177], face, { castKg: 9.084, yieldFraction: 0.625, pourKg: 9.084 / 0.625, densityKgPerM3: 7100, depthMm: 274.51 });
    expect(p.fit).toBe(9);
    expect(p.plate).toBe(Math.floor(0.6 * 950 * 700 / (272.36 * 227)));
    const mould = 950 * 700 * 344.51 * 1e-9 * 1500, pour = 9.084 / 0.625;
    expect(p.sandIron).toBe(Math.floor(mould / (5 * pour + pour / 7100 * 1500)));
    expect(p.n).toBe(4);
    // a part that does not fit is floor-moulded (0); one that fits once but breaks the plate rule is still one
    expect(impressionPlan([1000, 800], face, null).n).toBe(0);
    expect(impressionPlan([800, 500], face, null)).toMatchObject({ n: 1, fit: 1, plate: 0 });
  });
});

describe('3 / 4. HMC and CNC lathe capex through the UK book generator', () => {
  const cfg = JSON.parse(readFileSync('scripts/rate-refresh/2026-10-uk.json', 'utf8'));

  it('the twin-pallet HMC: £300,000 ESTIMATE, generated (machines.added), the book method, three shifts held', () => {
    const a = (cfg.machines.added as Array<{ id: string; capexGbp: number; capexBasis: string; hours: number; utilisation: number }>).find(x => x.id === 'mach-hmc-400')!;
    expect(a.capexGbp).toBe(300_000);
    expect([a.hours, a.utilisation]).toEqual([6000, 0.8]);
    expect((cfg.machines.groups as Array<{ id: string }>).some(g => g.id === 'cnc-hmc')).toBe(false);   // the dead group is gone
    const m = machine('mach-hmc-400');
    expect(m.buildup).toMatchObject({ annualDepreciation: Math.round(300_000 / 13), maintenance: 9000, indirectSupport: 15_000, financeCost: 6000,
      energy: 11_357, floorSpace: 8077, annualAvailableHours: 6000, machineUtilization: 0.8 });
    expect(m.computedRatePerHr).toBeCloseTo(72_511 / 4800, 6);   // £15.11/h (was £10.87)
    expect(m.sourceNote).toMatch(/Capex £300,000 = ESTIMATE/);
    expect(m.sourceNote).toContain(`US$249,990 = £${Math.round(RESEARCH.get('H1')!.gbp_at_book_fx!).toLocaleString('en-GB')}`);
    expect(m.sourceNote).toContain(`£${Math.round(RESEARCH.get('H3')!.gbp_at_book_fx!).toLocaleString('en-GB')}`);
    expect(m.sourceNote).toMatch(/It was £185,000/);
    const reg = readFileSync('scripts/rate-refresh/uk-2026-10/register.csv', 'utf8');
    expect(reg).toMatch(/"mach-hmc-400",[^\n]*"15\.11",[^\n]*added \(capex from research: review-round H1 \/ H3\)/);
  });

  it('the CNC lathe: £135,041 (UKRI Mazak award, 2024), its own group; the Mazak QT200 sized on it; hours held at 4,000 × 0.80', () => {
    const g = (cfg.machines.groups as Array<{ id: string; match: string; refId: string; refCapexGbp: number; basis: string }>).find(x => x.id === 'cnc-lathe')!;
    expect(g.refCapexGbp).toBe(RESEARCH.get('T4')!.value_num);
    expect(new RegExp(g.match).test('mach-mazak-qt200')).toBe(true);
    expect(g.basis).toMatch(/Hours held at the book’s convention \(the lathe 4,000 h × 0\.80\)|Hours held at the book's convention \(the lathe 4,000 h × 0\.80\)/);
    const three = (cfg.machines.groups as Array<{ id: string; match: string }>).find(x => x.id === 'cnc-3axis')!;
    expect(new RegExp(three.match).test('mach-lathe-cnc')).toBe(false);
    const m = machine('mach-lathe-cnc');
    expect(m.buildup).toMatchObject({ annualDepreciation: Math.round(135_041 / 13), maintenance: Math.round(135_041 * 0.03),
      indirectSupport: Math.round(135_041 * 0.05), financeCost: Math.round(135_041 / 2 * 0.04), energy: 6933, annualAvailableHours: 4000, machineUtilization: 0.8 });
    expect(m.computedRatePerHr).toBeCloseTo(computeMachineRateFromBuildup(m.buildup), 10);
    expect(m.computedRatePerHr).toBeCloseTo(12.16, 2);            // was £7.79/h
    expect(m.sourceNote).toMatch(/UKRI-4318 ’CNC Lathe machine’ £135,041/);
    // the QT200 keeps its size relative to the lathe, so the turning ranking still picks the lathe (£16.97 v £12.16)
    expect(machine('mach-mazak-qt200').computedRatePerHr).toBeGreaterThan(m.computedRatePerHr);
  });

  it('every country carries the new capital by its own rule: a local lathe group keeps its local capex, the rest AT PAR', () => {
    const LOCAL_LATHE = new Set(['CN', 'ID', 'TH', 'TW', 'VN', 'IN']);
    for (const r of Object.keys(REGIONAL_DATA) as ManufacturingRegion[]) {
      if (r === 'UK') continue;
      const lib = buildRegionalLibrary(book, r);
      const hmc = lib.machines.find(x => x.id === 'mach-hmc-400')!;
      expect(hmc.sourceNote, `${r} HMC`).toMatch(/capital AT PAR/);           // no book has an HMC capex group
      expect(hmc.buildup.annualDepreciation, `${r} HMC`).toBeGreaterThan(0);
      const lathe = lib.machines.find(x => x.id === 'mach-lathe-cnc')!;
      if (LOCAL_LATHE.has(r)) expect(lathe.sourceNote, `${r} lathe`).toMatch(/capex .*\(cnc-/);
      else expect(lathe.sourceNote, `${r} lathe`).toMatch(/capital AT PAR/);
    }
  });
});

/**
 * Review round (4 Nov 2026) — the four cost-model changes the user approved from
 * scripts/research/2026-11-review-round/{data.json, notes.md}:
 *
 *  1. Foundry indirect costs as NAMED rules (sand / gravity, iron and steel): new sand + disposal (£/t poured), ladle
 *     preheat (gas kWh/t poured), dust extraction and other plant electricity (kWh/t good casting — the last an ESTIMATE,
 *     grade D). Energy reaches the core as kWh, so every country prices it at its own tariff. What the research could not
 *     price is listed as not costed — on the rule basis and in the report standard's "Not in the cost model".
 *  2. Impressions per mould = min(free fit, patterns + gating ≤ 60 % of the plate, on iron sand : iron ≥ 5 : 1 at the
 *     mould thickness depth + 70 mm); the basis says which limit binds.
 *  3. The twin-pallet HMC's capex £185,000 → £300,000 ESTIMATE, generated by the UK book (it was hand-written).
 *  4. The CNC lathe's capex £56,004 → £135,041 (a UK public award), the lathe group of the UK book; hours unchanged.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { runCostInputRules } from '../src/engine/cost-input-rules/engine.js';
import { CAST_AND_MACHINE_RULES } from '../src/engine/cost-input-rules/commodities/cast-and-machine.js';
import { RULE_PATH_MAP } from '../src/engine/cost-input-rules/apply.js';
import { impressionPlan } from '../src/engine/cost-input-rules/commodities/casting.js';
import { IMPRESSION_LIMITS, SAND_LINE_CLASSES } from '../src/engine/modules/casting-advisor.js';
import { FOUNDRY_INDIRECT, NEW_SAND_GBP_PER_T_SAND, PLANT_OTHER_KWH_PER_T, NEW_SAND_BASIS, FOUNDRY_NOT_COSTED } from '../src/engine/casting-melt.js';
import { computeCastingDrivers } from '../src/engine/modules/casting.js';
import { DEFAULT_RATE_LIBRARY, recomputeMachineRates, computeMachineRateFromBuildup } from '../src/engine/rate-library.js';
import { buildRegionalLibrary, REGIONAL_DATA, type ManufacturingRegion } from '../src/engine/regional-rates.js';
import { reportStandardFor } from '../src/export/report-standard.js';

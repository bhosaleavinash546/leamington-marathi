/**
 * Hungary rate book (Oct 2026, docs/rates/hungary-rate-book-2026-10.md): Hungary's OWN rates, no unsourced UK
 * multiplier. What the research priced is the book's; what it could not price is AT PAR (×1) and says so — never the
 * old 0.97 / 0.70 factors.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { COUNTRY_BOOKS, machineGroupOf } from '../src/engine/country-books.js';
import { HUNGARY_BOOK } from '../src/engine/country-books/hu.js';
import { REGIONAL_DATA, buildRegionalLibrary } from '../src/engine/regional-rates.js';
import { DEFAULT_RATE_LIBRARY, recomputeMachineRates } from '../src/engine/rate-library.js';
import { costMeasuredPart } from '../server/services/bulk-run.js';

const UK = recomputeMachineRates(DEFAULT_RATE_LIBRARY);
const HU = buildRegionalLibrary(UK, 'HU');
const cfg = JSON.parse(readFileSync('scripts/rate-refresh/2026-10-hungary.json', 'utf8'));

describe('Hungary rate book', () => {
  it('is registered, generated from its dated config, at the MNB rate', () => {
    expect(COUNTRY_BOOKS.HU).toBe(HUNGARY_BOOK);
    expect(HUNGARY_BOOK.asOf).toBe('2026-10-30');
    expect(REGIONAL_DATA.HU.fxToGBP).toBe(cfg.fxPerGbp);
    expect(cfg.fxPerGbp).toBe(437.75);
    expect(readFileSync('src/engine/country-books/hu.ts', 'utf8')).toMatch(/GENERATED by `scripts\/country-book\.ts`/);
  });

  it('labour is Hungary\'s own (KSH total earnings + szocho), the engineer the one held rate and labelled', () => {
    for (const k of ['skilled', 'semiskilled', 'foundry', 'electronics', 'inspector', 'technician', 'supervisor'] as const) {
      expect(REGIONAL_DATA.HU.labour[k], k).toBeCloseTo(cfg.labour.categories[k].localPerHr / cfg.fxPerGbp, 3);
      expect(cfg.labour.categories[k].basis, k).toMatch(/WITHOUT the shift allowance/);
    }
    expect(cfg.labour.categories.engineer.basis).toMatch(/^HELD/);
  });

  it('no unsourced UK factor: held materials at par, held machine capital at par', () => {
    expect(REGIONAL_DATA.HU.materialMultiplier).toBe(1);
    expect(REGIONAL_DATA.HU.materialFactors).toEqual({ commodityResin: 1, engineeringResin: 1, highPerfResin: 1 });
    expect(HUNGARY_BOOK.machines.capitalHeldFactor).toBe(1);
    for (const m of HU.materials) {
      const uk = UK.materials.find(x => x.id === m.id)!;
      if (HUNGARY_BOOK.materials[m.id] || /^mat-al-billet-/.test(m.id) || /country price/.test(m.sourceNote)) continue;
      expect(m.pricePerKg, m.id).toBeCloseTo(uk.pricePerKg, 9);
      expect(m.sourceNote, m.id).toMatch(/at par \(no country factor\)/);
    }
  });

  it('every machine runs Hungary\'s operating model: 3 × 8 h (6,072 h), its tariff, rent and finance', () => {
    expect(HUNGARY_BOOK.machines.hoursPerYear).toBe(6072);
    const vf2 = HU.machines.find(m => m.id === 'mach-haas-vf2')!;
    expect(machineGroupOf(HUNGARY_BOOK, 'mach-haas-vf2')?.id).toBe('cnc-vmc-eu');
    expect(vf2.sourceNote).toMatch(/Haas VF-2 EU-series list €64,995/);
    const lathe = HU.machines.find(m => m.id === 'mach-lathe-cnc')!;
    expect(machineGroupOf(HUNGARY_BOOK, 'mach-lathe-cnc')).toBeNull();
    expect(lathe.sourceNote).toMatch(/AT PAR/);
  });

  it('every rate line of every real part costed in Hungary is Hungary\'s book', async () => {
    const baseline = JSON.parse(readFileSync('tests/fixtures/real-parts-baseline.json', 'utf8')) as
      { part: string; answers: Record<string, string>; geometry: never; outcome: { commodity?: string } }[];
    const bad: string[] = [];
    let costed = 0;
    for (const p of baseline) {
      const r = await costMeasuredPart(p.geometry, p.part, { partNumber: p.part, file: p.part, annualVolume: 50_000,
        ...(p.outcome.commodity ? { commodity: p.outcome.commodity } : {}) },
      p.answers, 'HU', { annualVolume: 50_000, deliveryTerms: 'EXW' }, UK, { partNumber: p.part, file: p.part, status: 'error' });
      if (r.status !== 'costed') continue;
      costed++;
      expect(r.trace!.rateBook, p.part).toMatch(/-HU$/);
      expect(r.breakdown!.logistics, p.part).toBe(0);
      for (const o of r.trace!.operations) {
        const m = HU.machines.find(x => x.id === o.machineId)!, l = HU.labour.find(x => x.id === o.labourId)!;
        if (Math.abs(o.machineRateUsed - m.computedRatePerHr) > 1e-6) bad.push(`${p.part} ${o.operationName} machine`);
        if (Math.abs(o.labourRateUsed - l.fullyLoadedRatePerHr) > 1e-6) bad.push(`${p.part} ${o.operationName} labour`);
      }
    }
    expect(costed).toBeGreaterThan(30);
    expect(bad).toEqual([]);
  }, 300_000);
});

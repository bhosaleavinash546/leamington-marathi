#!/usr/bin/env python3
"""
Write src/engine/country-books/world.ts — the registry of the world round's country books (30 Oct 2026). It imports
every book `scripts/country-book.ts` has written for a world-round config (scripts/rate-refresh/2026-10-world-<cc>.json)
and nothing else, so COUNTRY_BOOKS gains a country only when its book exists.
  python3 -I scripts/rate-refresh/world-2026-10/register-books.py
"""
import glob, json, os
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
rows = []
for p in sorted(glob.glob(os.path.join(ROOT, 'scripts/rate-refresh/2026-10-world-*.json'))):
    c = json.load(open(p))
    if os.path.exists(os.path.join(ROOT, c['bookFile'])):
        rows.append((c['region'], c['bookConst'], os.path.basename(c['bookFile']).replace('.ts', '.js')))
out = ['/**',
       ' * World rate round (30 Oct 2026) — the country books written from `scripts/rate-refresh/2026-10-world-<cc>.json`.',
       ' * GENERATED by `scripts/rate-refresh/world-2026-10/register-books.py`; do not edit by hand.',
       ' */',
       "import type { CountryBook } from '../country-books.js';"]
out += [f"import {{ {const} }} from './{f}';" for _, const, f in rows]
out += ['', 'export const WORLD_BOOKS: Record<string, CountryBook> = {']
out += [f'  {r}: {const},' for r, const, _ in rows]
out += ['};', '']
open(os.path.join(ROOT, 'src/engine/country-books/world.ts'), 'w').write('\n'.join(out))
print(f'world.ts: {len(rows)} books — {", ".join(r for r, _, _ in rows)}')

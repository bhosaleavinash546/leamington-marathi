// Renders the CostVision logo (indigo "cv" badge + blue wordmark — the same mark as the
// app header and the PDF footer) to a 2x PNG, written as src/brand/logo-png.ts so every
// export (the PCB workbook's sheets) embeds the identical, crisp image.
//   node scripts/brand-logo-png.mjs
import { chromium } from 'playwright';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const font = w => readFileSync(join(ROOT, `public/fonts/inter-latin-${w}-normal.woff2`)).toString('base64');
const W = 232, H = 48;   // CSS px; rendered at 2x
const html = `<!doctype html><html><head><style>
@font-face{font-family:Inter;font-weight:800;src:url(data:font/woff2;base64,${font(800)}) format('woff2')}
@font-face{font-family:Inter;font-weight:600;src:url(data:font/woff2;base64,${font(600)}) format('woff2')}
html,body{margin:0;background:transparent}
.l{width:${W}px;height:${H}px;display:flex;align-items:center;gap:10px;font-family:Inter}
.b{width:40px;height:40px;border-radius:10px;background:#4F46E5;color:#fff;font-weight:800;font-size:21px;display:grid;place-items:center;letter-spacing:-0.5px}
.w{display:flex;flex-direction:column;line-height:1}
.n{color:#2563EB;font-weight:800;font-size:24px;letter-spacing:-0.4px}
.t{color:#686F7D;font-weight:600;font-size:8.5px;letter-spacing:1.6px;margin-top:4px}
</style></head><body><div class="l"><div class="b">cv</div><div class="w"><div class="n">CostVision</div><div class="t">AI COST INTELLIGENCE</div></div></div></body></html>`;
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_PATH || undefined });
const page = await browser.newPage({ deviceScaleFactor: 2, viewport: { width: W, height: H } });
await page.setContent(html);
await page.evaluate(() => document.fonts.ready);
const png = await page.locator('.l').screenshot({ omitBackground: true });
await browser.close();
writeFileSync(join(ROOT, 'src/brand/logo-png.ts'),
  `// GENERATED by scripts/brand-logo-png.mjs — do not edit. ${W * 2}x${H * 2} PNG (2x), shown at ${W}x${H} px.\n`
  + `export const LOGO_PNG_BASE64 = '${png.toString('base64')}';\nexport const LOGO_PX = { width: ${W}, height: ${H} };\n`);
writeFileSync('/tmp/claude-0/-home-user-leamington-marathi/8bf32d1a-7485-5bd6-9947-7843ee6c5644/scratchpad/logo.png', png);
console.log('logo', png.length, 'bytes');

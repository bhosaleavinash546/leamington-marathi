@app.post("/v1/milan", tags=["milan"])
def milan(request: Annotated[MilanInput, Body()]) -> dict[str, Any]:
    """Ashtakoot Guna Milan from two births.

    Returns per-koot scores with their reasons and any exception that applies -
    never a bare total, and never a verdict (CLAUDE.md 3.5, 6.7). Both Moon
    positions are computed here from full birth input rather than accepted as
    parameters, because accepting them would be accepting computed values.
    """
    bride_facts = _facts(request.bride)
    groom_facts = _facts(request.groom)
    for label, facts in (("bride", bride_facts), ("groom", groom_facts)):
        if "chart" not in facts:
            raise HTTPException(
                status.HTTP_422_UNPROCESSABLE_ENTITY,
                detail=f"{label}: Guna Milan needs the Moon's nakshatra, which needs a birth time",
            )

    result = compute_milan(
        bride_moon_rashi=_moon(bride_facts)["rashi"],
        bride_moon_nakshatra=_moon(bride_facts)["nakshatra"],
        groom_moon_rashi=_moon(groom_facts)["rashi"],
        groom_moon_nakshatra=_moon(groom_facts)["nakshatra"],
    )
    return {
        "koots": [
            {
                "koot": k.koot,
                "points": k.points,
                "max_points": k.max_points,
                "evidence": list(k.evidence),
            }
            for k in result.koots
        ],
        "total": result.total,
        "max_total": result.max_total,
        "exceptions": [
            {"koot": e.koot, "key": e.key, "evidence": list(e.evidence)} for e in result.exceptions
        ],
        # CLAUDE.md 6.7: information, never a verdict. Stated in the payload so a
        # client cannot present the total as a recommendation without ignoring it.
        "presentation_rule": "koot_scores_are_information_not_a_verdict",
        "glossary": load_glossary(request.locale)["milan"],
        "disclaimer": disclaimer(request.locale),
    }


def _moon(facts: dict[str, Any]) -> dict[str, Any]:
    return next(g for g in facts["chart"]["grahas"] if g["key"] == Graha.MOON.value)



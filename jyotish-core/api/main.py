DESCRIPTION = """\
A deterministic Jyotish computation engine with a separately-validated narrative
layer.

**No number in any response is generated by a language model.** Every degree,
tithi, timestamp, dasha date, koot score and bala value comes from the
deterministic engine; the `/v1/narrative` endpoint receives computed facts and may
only phrase them, and a post-generation validator rejects prose containing any
figure absent from the facts.

Astronomical output is regression-tested against **दाते पंचांग (Date Panchang)**.
See `docs/GOLDEN_FILES.md` for the current verification status - at the time of
writing, agreement with the authority is scaffolded but not yet transcribed.

This is a traditional Jyotish interpretation tool. It is not a forecast of the
future, and it is not a substitute for medical, legal, financial or psychological
advice.
"""


@app.post("/v1/panchang", tags=["panchang"])
def panchang(
    birth: Annotated[BirthInput, Body()],
) -> dict[str, Any]:
    """The panchang of a day at a place.

    Needs no birth time: a day's panchang is a property of the date and place. When
    a time is supplied the response also carries the limbs *at that instant*,
    because the two differ and CLAUDE.md 4.3 requires both.
    """
    facts = _facts(birth)
    return {
        "panchang": facts["panchang"],
        "ephemeris": facts["ephemeris"],
        "confidence": facts["confidence"],
        "glossary": {
            ns: load_glossary(birth.locale)[ns]
            for ns in ("panchang", "tithi", "nakshatra", "yoga", "karana", "vara", "month")
        },
        "disclaimer": disclaimer(birth.locale),
    }



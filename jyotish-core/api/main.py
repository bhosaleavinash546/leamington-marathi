@app.post("/v1/chart", response_model=ChartFactsResponse, tags=["chart"])
def chart(birth: Annotated[BirthInput, Body()]) -> ChartFactsResponse:
    """The full ChartFacts document, schema-validated before it leaves.

    The glossary rides alongside rather than merged in, so the document itself stays
    free of Devanagari (CLAUDE.md 5) while a client still renders in one round trip.
    """
    return ChartFactsResponse(
        facts=_facts(birth),
        glossary=load_glossary(birth.locale),
        disclaimer=disclaimer(birth.locale),
    )


@app.post("/v1/chart/svg", tags=["chart"], response_class=Response)
def chart_svg(
    birth: Annotated[BirthInput, Body()],
    style: Annotated[str | None, Query(description="north_indian | south_indian")] = None,
    varga: Annotated[str, Query(description="D1 or any emitted varga, e.g. D9")] = "D1",
    degrees: Annotated[bool, Query(description="print degrees in each cell")] = False,
    table: Annotated[bool, Query(description="return the accessible table instead")] = False,
) -> Response:
    """A rendered kundali. North Indian diamond by default (CLAUDE.md 8).

    ``table=true`` returns the semantic HTML table alternative that CLAUDE.md 8
    requires for screen readers - the same data, not a summary of it.
    """
    facts = _facts(birth)
    if "chart" not in facts:
        raise HTTPException(
            status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=(
                "no chart without a birth time: the ascendant and houses are "
                "undefined, and CLAUDE.md 4.6 forbids defaulting to noon"
            ),
        )
    try:
        chart_style = chart_style_from_string(style)
    except ValueError as exc:
        raise HTTPException(status.HTTP_400_BAD_REQUEST, detail=str(exc)) from exc

    data = (
        rashi_chart(facts, birth.locale)
        if varga.upper() == "D1"
        else varga_chart(facts, varga.upper(), birth.locale)
    )
    if table:
        glossary = load_glossary(birth.locale)["chart"]
        body = render_table(
            data, headers=(glossary["house"], glossary["rashi_chart"], glossary["kundali"])
        )
        return Response(content=body, media_type="text/html; charset=utf-8")
    body = render(data, chart_style, show_degrees=degrees, show_sav=varga.upper() == "D1")
    return Response(content=body, media_type="image/svg+xml")


@app.post("/v1/chart/pdf", tags=["chart"], response_class=Response)
def chart_pdf(
    birth: Annotated[BirthInput, Body()],
    style: Annotated[str | None, Query()] = None,
) -> Response:
    """A print-clean kundali sheet at A4, locale-aware (CLAUDE.md 8).

    Font glyph coverage for the locale is verified before rendering, because a
    missing Devanagari glyph produces a blank rather than an error
    (CLAUDE.md 2.2).
    """
    facts = _facts(birth)
    try:
        chart_style = chart_style_from_string(style)
    except ValueError as exc:
        raise HTTPException(status.HTTP_400_BAD_REQUEST, detail=str(exc)) from exc
    pdf = render_pdf(facts, birth.locale, style=chart_style)
    safe_name = "".join(c for c in birth.name if c.isalnum() or c in " -_") or "kundali"
    return Response(
        content=pdf,
        media_type="application/pdf",
        headers={"Content-Disposition": f'attachment; filename="{safe_name}.pdf"'},
    )



@app.get("/health", response_model=HealthResponse, tags=["meta"])
def health(settings: Annotated[Settings, Depends(get_settings)]) -> HealthResponse:
    """Version and configuration. Includes the pinned ayanamsa constant.

    The constant, not just the name: CLAUDE.md 4.5 treats an ayanamsa redefinition
    as a breaking change, and an operator needs to be able to see which one is live
    without computing a chart.
    """
    info = build_ephemeris().info
    return HealthResponse(
        status="ok",
        engine_version=ENGINE_VERSION,
        chartfacts_schema_version=CHARTFACTS_SCHEMA_VERSION,
        ephemeris_provider=info.provider,
        ayanamsa_constant=info.ayanamsa_constant,
        authority="date_panchang",
        narrative_generation_enabled=settings.narrative_enabled,
        locales=list(SUPPORTED_LOCALES),
    )



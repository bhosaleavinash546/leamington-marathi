# ---------------------------------------------------------------------------
# Error handling
# ---------------------------------------------------------------------------


def _error(status_code: int, key: str, message: str, field: str | None = None) -> JSONResponse:
    return JSONResponse(
        status_code=status_code,
        content=ErrorResponse(
            errors=[ErrorDetail(key=key, message=message, field=field)]
        ).model_dump(),
    )


@app.exception_handler(InputError)
async def _input_error(_request: Any, exc: InputError) -> JSONResponse:
    """CLAUDE.md 3.1: reject silently-wrong input loudly."""
    return _error(status.HTTP_422_UNPROCESSABLE_ENTITY, "invalid_input", str(exc))


@app.exception_handler(CircumpolarError)
async def _circumpolar(_request: Any, exc: CircumpolarError) -> JSONResponse:
    """Sunrise is genuinely undefined, so the response says so.

    A 422 rather than a 500: the request is well-formed and the answer is that the
    quantity does not exist at that latitude on that date (CLAUDE.md 3.1).
    """
    return _error(
        status.HTTP_422_UNPROCESSABLE_ENTITY,
        "sunrise_undefined_at_this_latitude",
        f"{exc} The Hindu day begins at sunrise, so vara, the headline tithi and "
        "Ishtakaal are undefined here. This is not an error in the computation.",
    )


@app.exception_handler(ChartFactsError)
async def _facts_invalid(_request: Any, exc: ChartFactsError) -> JSONResponse:  # pragma: no cover
    """A document that fails its own schema is a server bug, not a client one."""
    return _error(status.HTTP_500_INTERNAL_SERVER_ERROR, "chartfacts_contract_violation", str(exc))


@app.exception_handler(PromptError)
async def _prompt_error(_request: Any, exc: PromptError) -> JSONResponse:
    return _error(status.HTTP_400_BAD_REQUEST, "unknown_section_or_locale", str(exc))


@app.exception_handler(PdfError)
async def _pdf_error(_request: Any, exc: PdfError) -> JSONResponse:  # pragma: no cover
    return _error(status.HTTP_500_INTERNAL_SERVER_ERROR, "pdf_render_failed", str(exc))



@app.get("/v1/dasha/subperiods", tags=["dasha"])
def dasha_subperiods(
    lord: Annotated[str, Query(description="the parent period's lord")],
    start_utc: Annotated[str, Query()],
    end_utc: Annotated[str, Query()],
    level: Annotated[int, Query(ge=1, le=3, description="the parent's level")],
) -> list[dict[str, Any]]:
    """The nine children of one dasha period.

    Exists so the UI's four-level tree (CLAUDE.md 8) can expand a level on demand.
    A full four-level tree is 7380 nodes, too many to ship with every chart and far
    too many to let a browser compute - CLAUDE.md N1 keeps every dasha date in the
    engine.

    The parent is reconstructed from its lord and bounds rather than from a birth
    input, because sub-period division is *proportional*: the children of a period
    depend only on its span and its lord, so nothing about the birth is needed and
    nothing about it need be sent.
    """
    try:
        parent_lord = Graha(lord)
    except ValueError as exc:
        raise HTTPException(
            status.HTTP_400_BAD_REQUEST, detail=f"unknown dasha lord {lord!r}"
        ) from exc
    try:
        start = dt.datetime.fromisoformat(start_utc.replace("Z", "+00:00"))
        end = dt.datetime.fromisoformat(end_utc.replace("Z", "+00:00"))
    except ValueError as exc:
        raise HTTPException(status.HTTP_400_BAD_REQUEST, detail=str(exc)) from exc
    if end <= start:
        raise HTTPException(status.HTTP_400_BAD_REQUEST, detail="end_utc must follow start_utc")

    parent = DashaPeriod(level=level, lord=parent_lord, start_utc=start, end_utc=end)
    return [
        {
            "level": child.level,
            "lord": child.lord.value,
            "start_utc": iso_utc(child.start_utc),
            "end_utc": iso_utc(child.end_utc),
        }
        for child in subperiods(parent, YearLength.SOLAR_365_2425)
    ]



"""The FastAPI application.

CLAUDE.md 1: "FastAPI (Python 3.12) - **ORCHESTRATION ONLY**. validates input ->
calls engine -> assembles ChartFacts JSON."

Every route here does exactly those three things. There is no Jyotish arithmetic in
this module or anywhere else under ``api/``; a test asserts that ``core/`` imports
nothing from here, and the reverse dependency is the only one that exists.

Route groups:

===================================  ==========================================
``/health``                          version and configuration, no input
``/v1/panchang``                     a day's panchang for a date and place
``/v1/chart``                        the full schema-valid ChartFacts document
``/v1/chart/svg`` ``/v1/chart/pdf``  rendered kundali (CLAUDE.md 8)
``/v1/milan``                        Ashtakoot from two births
``/v1/narrative``                    validated prose (CLAUDE.md 6)
``/v1/places``                       offline geocoder (CLAUDE.md 2.2)
``/v1/privacy/*``                    consent, export, delete (CLAUDE.md 10)
===================================  ==========================================
"""


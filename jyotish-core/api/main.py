def _facts(birth: BirthInput, *, now: dt.datetime | None = None) -> dict[str, Any]:
    """Compute and validate ChartFacts for a request.

    Validation runs on every response, not only in tests: a document that fails its
    own schema is a contract violation and must not reach a client
    (CLAUDE.md 5).
    """
    facts = build_chart_facts(compute_full_reading(birth.to_engine(), now=now or utc_now()))
    validate_chart_facts(facts)
    return facts

@app.post("/v1/narrative", response_model=NarrativeResponse, tags=["narrative"])
def narrative(
    request: Annotated[NarrativeRequest, Body()],
    service: Annotated[NarrativeService, Depends(get_narrative_service)],
    settings: Annotated[Settings, Depends(get_settings)],
) -> NarrativeResponse:
    """Validated prose for one or more sections.

    The facts are **recomputed here** from the birth input; a caller cannot supply
    them. Accepting facts would let a client feed the model arbitrary numbers,
    which is the exact hole CLAUDE.md N1 exists to close.

    Every returned section has passed the post-generation validator: the
    CLAUDE.md 6.6/6.7 blocklist for its locale, and a numeric-provenance check that
    rejects any figure absent from the facts.
    """
    locale = request.locale or request.birth.locale
    facts = _facts(request.birth)
    requested = tuple(request.sections) if request.sections else SECTIONS
    unknown = set(requested) - set(SECTIONS)
    if unknown:
        raise HTTPException(
            status.HTTP_400_BAD_REQUEST,
            detail=f"unknown section(s) {sorted(unknown)}; known: {list(SECTIONS)}",
        )

    sections = service.generate_all(facts, locale, sections=requested)
    return NarrativeResponse(
        sections=[
            NarrativeSectionOut(
                section=s.section,
                locale=s.locale,
                text=s.text,
                is_refusal=s.is_refusal,
                cached=s.cached,
                model=s.model,
                prompt_version=s.prompt_version,
                warnings=list(s.warnings),
            )
            for s in sections
        ],
        disclaimer=disclaimer(locale),
        generation_enabled=settings.narrative_enabled,
    )


